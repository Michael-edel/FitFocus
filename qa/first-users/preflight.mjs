// HTTP fixture checks, not a first-user or UX run. Uses the dedicated port4250 only.
import assert from 'node:assert/strict';
const origin='http://127.0.0.1:4250';
const call=(path,options={})=>fetch(origin+path,options);
const health=await (await call('/__qa/health')).json();
assert.equal(health.productionBindings,false);
assert.equal(health.outboundHttp,false);
const shell=await call('/'); assert.equal(shell.status,200);
assert.match(shell.headers.get('content-security-policy'),/connect-src 'self'/);
assert.equal((await (await call('/api/me')).json()).user,null);
assert.equal((await call('/api/profile')).status,401);
assert.equal((await call('/api/auth/google/start')).status,200);
const login=await call('/__qa/login',{method:'POST',body:new URLSearchParams({email:health.email}),redirect:'manual'});
assert.equal(login.status,302); assert.equal(login.headers.get('location'),'/?auth=google');
const cookie=login.headers.get('set-cookie').split(';')[0];
const me=await (await call('/api/me',{headers:{Cookie:cookie}})).json();
assert.equal(me.user.email,health.email);
const headers={Cookie:cookie,'Content-Type':'application/json','X-FitFocus-State-Account':me.user.sub,'X-FitFocus-State-Session':me.stateSync.sessionId};
const before=await (await call('/api/bootstrap',{headers})).json(); assert.equal(before.profile,null);
const put=await call('/api/profile',{method:'PUT',headers,body:JSON.stringify({id:me.user.sub,name:'Synthetic preflight',baseVersion:0,plan:'free'})});
assert.equal(put.status,200); assert.equal((await put.json()).version,1);
assert.equal((await (await call('/api/bootstrap',{headers})).json()).profile.name,'Synthetic preflight');
assert.equal((await call('/api/profile',{method:'PUT',headers:{Cookie:cookie,'Content-Type':'application/json'},body:'{}'})).status,403);
assert.equal((await call('/api/profile',{method:'PUT',headers:{...headers,Origin:'https://fitfocus.pages.dev'},body:'{}'})).status,403);
const ai=await (await call('/api/ai',{method:'POST',headers,body:JSON.stringify({feature:'personal_plan'})})).json();
assert.equal(JSON.parse(ai.text).model,'local-qa-fixture');
const payment=await call('/api/billing/checkout',{method:'POST',headers,body:JSON.stringify({plan:'pro'})});
assert.equal(payment.status,503); assert.equal(payment.headers.get('location'),null);
assert.equal((await payment.json()).error,'QA_STRIPE_SANDBOX_NOT_CONFIGURED');
